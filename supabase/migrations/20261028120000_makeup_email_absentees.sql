-- ============================================================================
-- RHS Music Platform — Make-up email: derive absentees from the roll
-- ============================================================================
-- Idempotent — create or replace only; safe to re-run.
--
-- WHAT WAS WRONG
--   `makeup_email_context()` (036) and `begin_makeup_email_campaign()` selected
--   their recipients from `attendance_records ar where ar.status = 'absent'`.
--   No row can ever carry that status: `override_attendance()` *deletes* the
--   row when a mark is set to absent (016) and a scan only ever writes present
--   or late. "Absent" and "no record" are the same stored state in this schema
--   (docs/FEATURE_DECISIONS.md §1), so the recipient list was always empty and
--   the composer could never email anyone. `supabase/tests/event_emails.sql`
--   passed because its fixtures inserted `status = 'absent'` rows directly,
--   which the application cannot produce.
--
-- WHAT THIS DOES
--   Expected roster − attendance records = absent.
--
--     expected : an active membership in the event's program whose profile is
--                not deactivated and whose roles are not staff (director /
--                secretary) — the same roster every other attendance RPC
--                measures (`get_event_attendance_summary`, `attendance_report_rows`).
--     has a mark: a record for this event with status present, late or excused.
--                Late is not an absence for make-up and an excused absence is
--                already resolved. A record whose status is null or 'absent'
--                (legacy rows written before 016) still counts as absent — the
--                query never keys off the status alone.
--
--   A student with no record for the event is therefore an absentee, which is
--   what a teacher means by "who missed it". Teacher overrides are respected
--   for free: marking somebody present/late/excused takes them off the list.
--
--   Students who are expected and absent but cannot be emailed (no sign-in
--   account, no address, an unconfirmed address) are returned in a separate
--   `unreachable` array with the reason, so the composer names them instead of
--   dropping them silently. `roster_size` and `absent_count` let the composer
--   tell "everyone had a record" apart from "the query failed".
--
--   `makeup_email_context()` recipients now carry `email`, per the owner's
--   request that the composer show the teacher the address each message goes
--   to. This reverses the "no addresses to the browser" note in 036: the read
--   is still staff-only (`is_ensemble_staff`) and still refuses everyone else,
--   and the delivery logs still store no copy of an address.
--
-- ROLLBACK
--   Re-apply the two function definitions from 036_event_email_notifications.sql
--   in a new timestamped migration — do not edit this file or 036. That restores
--   the `status = 'absent'` selector (and the empty list it produces) and
--   removes `email`, `roster_size`, `absent_count` and `unreachable`.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. The composer's read: who is expected, who is absent, who is reachable
-- ---------------------------------------------------------------------------
create or replace function public.makeup_email_context(p_event uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_profile    uuid := public.current_profile_id();
  v_event      record;
  v_reason     text;
  v_can_send   boolean := false;
  v_roster     integer := 0;
  v_absent     integer := 0;
  v_recipients jsonb;
  v_unreachable jsonb;
begin
  select ev.id, ev.name, ev.date, ev.end_date, ev.all_day, ev.location, ev.archived,
         ev.ensemble_id, e.name as program_name, e.active as program_active
    into v_event
    from public.events ev
    join public.ensembles e on e.id = ev.ensemble_id
   where ev.id = p_event;

  if not found then
    return jsonb_build_object('ok', false, 'message', 'That event does not exist.');
  end if;

  if v_profile is null or not public.is_ensemble_staff(v_event.ensemble_id) then
    return jsonb_build_object(
      'ok', false,
      'message', 'Only this program''s staff can email students about an event.'
    );
  end if;

  -- The same checks the sender repeats, in the order the screen explains them.
  if v_event.archived then
    v_reason := 'This event is archived, so make-up emails are off.';
  elsif not v_event.program_active then
    v_reason := 'This program is archived, so make-up emails are off.';
  elsif v_event.end_date is null then
    v_reason := 'This event has no end time. Add one before make-up emails can be sent.';
  elsif v_event.end_date <= v_event.date then
    v_reason := 'This event''s end time is not after its start, so make-up emails stay off.';
  elsif now() < v_event.end_date then
    v_reason := 'Available after this event ends.';
  else
    v_can_send := true;
  end if;

  -- One derived set, read once: everyone expected at this event, whether they
  -- have a mark, and whether an address can actually reach them.
  select count(*),
         count(*) filter (where y.absent),
         coalesce(
           jsonb_agg(
             jsonb_build_object(
               'user_id', y.user_id,
               'name',    y.name,
               'section', y.section,
               'email',   y.email,
               'status',  'absent'
             )
             order by y.name
           ) filter (where y.absent and y.reachable),
           '[]'::jsonb
         ),
         coalesce(
           jsonb_agg(
             jsonb_build_object(
               'user_id', y.user_id,
               'name',    y.name,
               'section', y.section,
               'reason',  y.reason
             )
             order by y.name
           ) filter (where y.absent and not y.reachable),
           '[]'::jsonb
         )
    into v_roster, v_absent, v_recipients, v_unreachable
    from (
      select m.user_id,
             coalesce(nullif(p.display_name, ''), nullif(p.full_name, ''), 'Student') as name,
             coalesce(s.name, '') as section,
             (case when u.id is null then '' else coalesce(u.email, '') end)::text as email,
             -- Absent = expected, and no record that resolves the event.
             not exists (
               select 1
                 from public.attendance_records ar
                where ar.event_id = p_event
                  and ar.student_id = m.user_id
                  and ar.status in ('present', 'late', 'excused')
             ) as absent,
             (u.id is not null
              and coalesce(u.email, '') <> ''
              and u.email_confirmed_at is not null) as reachable,
             case
               when u.id is null then 'no_sign_in'
               when coalesce(u.email, '') = '' then 'no_address'
               when u.email_confirmed_at is null then 'unconfirmed'
               else null
             end as reason
        from public.memberships m
        join public.profiles p on p.id = m.user_id
        left join public.sections s on s.id = m.section_id
        left join auth.users u on u.id::text = p.auth_user_id
       where m.ensemble_id = v_event.ensemble_id
         and m.active
         and not p.deactivated
         and not ('director' = any (m.roles))
         and not ('secretary' = any (m.roles))
    ) y;

  return jsonb_build_object(
    'ok',          true,
    'can_send',    v_can_send,
    'reason',      v_reason,
    'event', jsonb_build_object(
      'id',       v_event.id,
      'name',     v_event.name,
      'date',     v_event.date,
      'end_date', v_event.end_date,
      'all_day',  v_event.all_day,
      'location', v_event.location,
      'archived', v_event.archived
    ),
    'program_name',   v_event.program_name,
    'teacher_name',   coalesce(
                        (select coalesce(nullif(display_name, ''), nullif(full_name, ''), '')
                           from public.profiles where id = v_profile),
                        ''),
    'roster_size',    v_roster,
    'absent_count',   v_absent,
    'recipients',     v_recipients,
    'unreachable',    v_unreachable
  );
end
$$;

comment on function public.makeup_email_context(uuid) is
  'For one event, staff only: whether make-up email is allowed right now and why not, the event/program/teacher names, the roster size, and the absentees — those reachable by email in `recipients` (with the address they will be sent to) and those who are absent but unreachable in `unreachable`, each with the reason. "Absent" means expected at the event with no present/late/excused record, because an absent mark deletes the row.';

revoke all on function public.makeup_email_context(uuid) from public, anon;
grant execute on function public.makeup_email_context(uuid) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. The sender's recipient set — the same rule, frozen from the database
-- ---------------------------------------------------------------------------
create or replace function public.begin_makeup_email_campaign(
  p_event        uuid,
  p_actor        uuid,
  p_operation    uuid,
  p_subject      text,
  p_instructions text,
  p_body_template text,
  p_recipients   uuid[] default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event       record;
  v_campaign    public.event_makeup_campaigns%rowtype;
  v_subject     text := btrim(coalesce(p_subject, ''));
  v_instructions text := coalesce(p_instructions, '');
  v_body        text := coalesce(p_body_template, '');
  v_recent      integer;
  v_eligible    integer;
  v_rows        jsonb;
begin
  if p_event is null or p_actor is null or p_operation is null then
    return jsonb_build_object('ok', false, 'message', 'The event, teacher and operation are required.');
  end if;
  if v_subject = '' then
    return jsonb_build_object('ok', false, 'message', 'Add a subject before sending.');
  end if;
  if length(v_subject) > 200 then
    return jsonb_build_object('ok', false, 'message', 'The subject must be 200 characters or fewer.');
  end if;
  if length(v_instructions) > 4000 then
    return jsonb_build_object('ok', false, 'message', 'The make-up instructions must be 4,000 characters or fewer.');
  end if;
  if length(v_body) > 8000 then
    return jsonb_build_object('ok', false, 'message', 'The message must be 8,000 characters or fewer.');
  end if;
  if v_body = '' then
    return jsonb_build_object('ok', false, 'message', 'Add a message before sending.');
  end if;

  select ev.id, ev.name, ev.date, ev.end_date, ev.archived,
         ev.ensemble_id, e.name as program_name, e.active as program_active
    into v_event
    from public.events ev
    join public.ensembles e on e.id = ev.ensemble_id
   where ev.id = p_event;

  if not found then
    return jsonb_build_object('ok', false, 'message', 'That event does not exist.');
  end if;

  if not public.has_permission_for(p_actor, v_event.ensemble_id, 'attendance.mark_present') then
    return jsonb_build_object(
      'ok', false,
      'message', 'You do not have permission to email students in this program.'
    );
  end if;

  if v_event.archived then
    return jsonb_build_object('ok', false, 'message', 'This event is archived, so make-up emails are off.');
  end if;
  if not v_event.program_active then
    return jsonb_build_object('ok', false, 'message', 'This program is archived, so make-up emails are off.');
  end if;
  if v_event.end_date is null or v_event.end_date <= v_event.date then
    return jsonb_build_object('ok', false, 'message', 'This event has no valid end time.');
  end if;
  if now() < v_event.end_date then
    return jsonb_build_object('ok', false, 'message', 'Available after this event ends.');
  end if;

  -- One operation id, one campaign. A repeated request resumes it instead of
  -- creating a second send, and accepted recipients are never selected again.
  select * into v_campaign
    from public.event_makeup_campaigns c
   where c.created_by = p_actor
     and c.client_operation_id = p_operation;

  if v_campaign.id is not null and v_campaign.event_id <> p_event then
    return jsonb_build_object(
      'ok', false,
      'message', 'That send operation belongs to a different event. Reload and try again.'
    );
  end if;

  if v_campaign.id is null then
    select count(*) into v_recent
      from public.event_makeup_campaigns c
     where c.created_by = p_actor
       and c.created_at > now() - interval '10 minutes';
    if v_recent >= 10 then
      return jsonb_build_object(
        'ok', false,
        'message', 'Too many email runs in a short time. Wait a few minutes and try again.'
      );
    end if;

    insert into public.event_makeup_campaigns
      (event_id, created_by, client_operation_id, subject, instructions, body_template, event_start, event_end)
    values
      (p_event, p_actor, p_operation, v_subject, v_instructions, v_body, v_event.date, v_event.end_date)
    returning * into v_campaign;
  end if;

  -- The eligible set: expected at the event, absent, and reachable by email.
  -- Expected − present/late/excused = absent, exactly as the context derives it.
  -- The browser can narrow this with p_recipients, never widen it.
  select count(*) into v_eligible
    from public.memberships m
    join public.profiles p on p.id = m.user_id
    join auth.users u      on u.id::text = p.auth_user_id
   where m.ensemble_id = v_event.ensemble_id
     and m.active
     and not p.deactivated
     and coalesce(u.email, '') <> ''
     and u.email_confirmed_at is not null
     and not ('director' = any (m.roles))
     and not ('secretary' = any (m.roles))
     and not exists (
       select 1
         from public.attendance_records ar
        where ar.event_id = p_event
          and ar.student_id = m.user_id
          and ar.status in ('present', 'late', 'excused')
     )
     and (p_recipients is null or m.user_id = any (p_recipients));

  if v_eligible > 500 then
    return jsonb_build_object(
      'ok', false,
      'message', 'This event has more than 500 eligible recipients. Send in smaller groups.'
    );
  end if;

  insert into public.event_makeup_deliveries (campaign_id, user_id)
  select v_campaign.id, m.user_id
    from public.memberships m
    join public.profiles p on p.id = m.user_id
    join auth.users u      on u.id::text = p.auth_user_id
   where m.ensemble_id = v_event.ensemble_id
     and m.active
     and not p.deactivated
     and coalesce(u.email, '') <> ''
     and u.email_confirmed_at is not null
     and not ('director' = any (m.roles))
     and not ('secretary' = any (m.roles))
     and not exists (
       select 1
         from public.attendance_records ar
        where ar.event_id = p_event
          and ar.student_id = m.user_id
          and ar.status in ('present', 'late', 'excused')
     )
     and (p_recipients is null or m.user_id = any (p_recipients))
  on conflict (campaign_id, user_id) do nothing;

  -- Return only work still to do: an accepted recipient is never re-sent by a
  -- retry of this operation. Attendance is read again here, so a correction
  -- made between opening the composer and sending excludes that student.
  select coalesce(
           jsonb_agg(
             jsonb_build_object(
               'delivery_id', d.id,
               'user_id',     d.user_id,
               'name',        coalesce(nullif(p.display_name, ''), nullif(p.full_name, ''), 'Student'),
               'email',       u.email,
               'section',     coalesce(s.name, ''),
               'status',      d.status,
               'attempts',    d.attempts
             )
             order by coalesce(nullif(p.display_name, ''), p.full_name)
           ),
           '[]'::jsonb
         )
    into v_rows
    from public.event_makeup_deliveries d
    join public.profiles p on p.id = d.user_id
    join auth.users u      on u.id::text = p.auth_user_id
    left join public.memberships m on m.user_id = d.user_id
                                  and m.ensemble_id = v_event.ensemble_id
    left join public.sections s on s.id = m.section_id
   where d.campaign_id = v_campaign.id
     and d.status <> 'accepted'
     -- A chunked send asks for its own slice. Without this, the second chunk
     -- would also pick up the first chunk's failures and retry them
     -- automatically, which is exactly what a failed-recipient retry is for.
     and (p_recipients is null or d.user_id = any (p_recipients));

  return jsonb_build_object(
    'ok',          true,
    'campaign_id', v_campaign.id,
    'event_id',    v_event.id,
    'event_name',  v_event.name,
    'event_start', v_event.date,
    'event_end',   v_event.end_date,
    'event_archived', v_event.archived,
    'program_name', v_event.program_name,
    'teacher_name', coalesce(
                      (select coalesce(nullif(display_name, ''), nullif(full_name, ''), '')
                         from public.profiles where id = p_actor),
                      ''),
    'recipients',  v_rows
  );
end
$$;

comment on function public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[]) is
  'Starts or resumes one make-up email operation for a teacher. Re-checks staff authority, the event end time, archived state and the frozen recipient set — an expected student with no present/late/excused record, reachable by email — and returns only recipients not yet accepted. Service-role only, called after the Edge Function verifies the JWT.';

revoke all on function public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[]) from public, anon, authenticated;
grant execute on function public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[]) to service_role;

-- ---------------------------------------------------------------------------
-- 3. Verification
-- ---------------------------------------------------------------------------
do $$
declare
  v_context  text := pg_get_functiondef('public.makeup_email_context(uuid)'::regprocedure);
  v_begin    text := pg_get_functiondef(
                       'public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[])'::regprocedure);
begin
  -- The broken selector — a stored 'absent' status that the application can
  -- never produce — must be gone from both functions.
  if position('ar.status = ''absent''' in v_context) > 0
     or position('ar.status = ''absent''' in v_begin) > 0 then
    raise exception 'FAIL: a make-up recipient query still selects a stored absent status';
  end if;
  if position('ar.status in (''present'', ''late'', ''excused'')' in v_context) = 0
     or position('ar.status in (''present'', ''late'', ''excused'')' in v_begin) = 0 then
    raise exception 'FAIL: a make-up recipient query does not resolve a mark';
  end if;

  -- Both must ignore the opt-out that governs the upcoming-events digest: a
  -- make-up email is a direct staff message, not the digest.
  if position('email_upcoming_events' in v_context) > 0
     or position('email_upcoming_events' in v_begin) > 0 then
    raise exception 'FAIL: the digest opt-out leaked into the make-up recipient rule';
  end if;

  -- Access is unchanged: staff call the context, the sender is service-role only.
  if not has_function_privilege('authenticated', 'public.makeup_email_context(uuid)', 'EXECUTE') then
    raise exception 'FAIL: authenticated cannot execute makeup_email_context()';
  end if;
  if has_function_privilege('anon', 'public.makeup_email_context(uuid)', 'EXECUTE') then
    raise exception 'FAIL: anon can execute makeup_email_context()';
  end if;
  if has_function_privilege('authenticated',
       'public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[])', 'EXECUTE') then
    raise exception 'FAIL: authenticated can execute begin_makeup_email_campaign()';
  end if;
  if not has_function_privilege('service_role',
       'public.begin_makeup_email_campaign(uuid, uuid, uuid, text, text, text, uuid[])', 'EXECUTE') then
    raise exception 'FAIL: service_role cannot execute begin_makeup_email_campaign()';
  end if;

  raise notice 'OK — make-up recipients are the expected roster minus its present/late/excused records';
end
$$;
